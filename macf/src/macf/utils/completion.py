"""Shell completion for ``macf_tools``, as a script the shell sources.

``macf_tools completion bash`` (or ``zsh``) prints a script. Commands and flags complete
from a table taken from the parser when the script is printed, so the script matches the
``macf_tools`` that printed it. ``harness attach <TAB>`` asks ``macf_tools completion
--candidates`` for the agents on this endpoint and the declared remotes (utils/roster.py),
each remote bounded by a timeout, so an unplugged remote costs at most that timeout and
offers nothing.

Hand-written rather than argcomplete: a completion that imports and runs the whole
parser on every keystroke, through an optional dependency most installs don't have, is
the reason tab completion was never set up here. The script below needs only the shell.

Both scripts run on the shells a MacBook has: bash 3.2 (no associative arrays, so the
table is a ``case``) and zsh.
"""
from __future__ import annotations

import argparse
from typing import Dict, List

#: The command whose next word is an agent name.
ATTACH_PATH = "harness attach"


def command_tree(parser: argparse.ArgumentParser) -> Dict[str, List[str]]:
    """Each command path (``""``, ``"harness"``, ``"harness attach"``) and the words that
    may follow it: its subcommands, then its visible flags. A flag whose help is
    suppressed stays hidden here too."""
    tree: Dict[str, List[str]] = {}

    def walk(p: argparse.ArgumentParser, path: str) -> None:
        words: List[str] = []
        for action in p._actions:
            if isinstance(action, argparse._SubParsersAction):
                for name, child in action.choices.items():
                    words.append(name)
                    walk(child, f"{path} {name}".strip())
            elif action.option_strings and action.help is not argparse.SUPPRESS:
                words.extend(action.option_strings)
        tree[path] = list(dict.fromkeys(words))

    walk(parser, "")
    return tree


def _case_table(tree: Dict[str, List[str]], indent: str) -> str:
    """The table as a shell ``case`` on the command path, one arm per path."""
    arms = []
    for path in sorted(tree):
        words = " ".join(w for w in tree[path] if "'" not in w)
        arms.append(f"{indent}'{path}') echo '{words}' ;;")
    return "\n".join(arms)


def render_bash(tree: Dict[str, List[str]], prog: str = "macf_tools") -> str:
    """The bash script. ``@`` is one of bash's word breaks, so the word being completed
    is read from the line itself, and each candidate is trimmed to the part after the
    last break before bash puts it in place."""
    return f"""# {prog} bash completion -- generated by: {prog} completion bash
# Load it with:  source <({prog} completion bash)   (or save it and source the file)
__{prog}_words() {{
    case "$1" in
{_case_table(tree, "        ")}
    esac
}}

_{prog}() {{
    local cur="${{COMP_WORDS[COMP_CWORD]}}" mpath="" w i
    for ((i = 1; i < COMP_CWORD; i++)); do
        w="${{COMP_WORDS[i]}}"
        case "$w" in -*) continue ;; esac
        case " $(__{prog}_words "$mpath") " in
            *" $w "*) mpath="${{mpath:+$mpath }}$w" ;;
        esac
    done
    COMPREPLY=()
    if [[ "$mpath" == "{ATTACH_PATH}" && "$cur" != -* ]]; then
        local line="${{COMP_LINE:0:COMP_POINT}}"
        local word="${{line##* }}"
        local n=$(( ${{#word}} - ${{#cur}} )) c
        while IFS= read -r c; do
            [ -n "$c" ] && COMPREPLY+=("${{c:n}}")
        done < <("${{COMP_WORDS[0]}}" completion --candidates --prefix "$word" 2>/dev/null)
        return 0
    fi
    COMPREPLY=($(compgen -W "$(__{prog}_words "$mpath")" -- "$cur"))
}}
complete -F _{prog} {prog}
"""


def render_zsh(tree: Dict[str, List[str]], prog: str = "macf_tools") -> str:
    """The zsh script. An agent's candidates carry their endpoint as the description, and
    match ignoring case, as the candidates command already filtered them."""
    return f"""#compdef {prog}
# {prog} zsh completion -- generated by: {prog} completion zsh
# Load it with:  source <({prog} completion zsh)   (after compinit)
__{prog}_words() {{
    case "$1" in
{_case_table(tree, "        ")}
    esac
}}

_{prog}() {{
    # Not "path": in zsh that name is tied to PATH.
    local mpath="" w i
    for (( i = 2; i < CURRENT; i++ )); do
        w="${{words[i]}}"
        [[ "$w" == -* ]] && continue
        [[ " $(__{prog}_words "$mpath") " == *" $w "* ]] && mpath="${{mpath:+$mpath }}$w"
    done
    if [[ "$mpath" == "{ATTACH_PATH}" && "${{words[CURRENT]}}" != -* ]]; then
        local -a cands
        cands=("${{(@f)$(${{words[1]}} completion --candidates --describe --prefix "${{words[CURRENT]}}" 2>/dev/null)}}")
        cands=(${{cands:#}})
        (( ${{#cands}} )) && _describe -t agents 'agent' cands -M 'm:{{a-zA-Z}}={{A-Za-z}}'
        return 0
    fi
    local -a opts
    opts=(${{=$(__{prog}_words "$mpath")}})
    compadd -a opts
}}
(( $+functions[compdef] )) && compdef _{prog} {prog}
"""


def render(shell: str, parser: argparse.ArgumentParser, prog: str = "macf_tools") -> str:
    tree = command_tree(parser)
    if shell == "bash":
        return render_bash(tree, prog)
    if shell == "zsh":
        return render_zsh(tree, prog)
    raise ValueError(f"no completion script for {shell!r}; bash or zsh")


def candidate_lines(pairs: List[tuple], describe: bool) -> List[str]:
    """The candidates command's output: a word per line, or ``word:description`` for zsh's
    ``_describe``, which splits on the first unescaped colon."""
    if not describe:
        return [w for w, _ in pairs]
    return [f"{w.replace(':', chr(92) + ':')}:{d}" for w, d in pairs]
